def lookup_job(
    conn: Conn,
    apply_url_norm: str,
    source: str,
    external_id: str,
) -> int | None:
    row = conn.execute(
        "SELECT id FROM jobs WHERE apply_url_norm = ?",
        (apply_url_norm,),
    ).fetchone()
    if row:
        return int(row["id"])
    ext = (external_id or "").strip()
    if ext:
        row = conn.execute(
            "SELECT id FROM jobs WHERE source = ? AND external_id = ?",
            (source, ext),
        ).fetchone()
        if row:
            return int(row["id"])
    return None


def upsert_job(
    conn: Conn,
    profile: Profile,
    *,
    apply_url: str,
    hosted_url: str,
    source: str,
    external_id: str,
    company_id: int | None,
    company: str,
    title: str,
    location_raw: str,
    description_text: str,
    raw_json: str,
    ats: str,
    employment_hint: str | None = None,
) -> tuple[str, int | None]:
    col_url, norm = job_identity(apply_url, hosted_url, source, external_id)
    if norm is None:
        return "skip", None
    status, reason = hard_filter(
        profile,
        title=title,
        location_raw=location_raw,
        description_text=description_text,
        employment_hint=employment_hint,
    )
    now = utc_now()
    ext_store = (external_id or "").strip() or None
    job_title = (title or "").strip() or "(untitled)"
    existing = lookup_job(conn, norm, source, external_id)
    if existing is not None:
        conn.execute(
            """
            UPDATE jobs
            SET apply_url = ?,
                last_seen_at = ?,
                is_active = 1,
                title = ?,
                location_raw = ?,
                description_text = ?,
                raw_json = ?,
                hard_status = ?,
                hard_reason = ?,
                company = ?,
                company_id = ?,
                ats = ?,
                external_id = ?
            WHERE id = ?
            """,
            (
                col_url,
                now,
                job_title,
                location_raw,
                description_text,
                raw_json,
                status,
                reason,
                company,
                company_id,
                ats,
                ext_store,
                existing,
            ),
        )
        conn.commit()
        return "update", existing
    cur = conn.execute(
        """
        INSERT INTO jobs (
          apply_url, apply_url_norm, source, external_id, company_id, company,
          title, location_raw, description_text, raw_json,
          first_seen_at, last_seen_at, is_active, hard_status, hard_reason, ats
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?, ?)
        """,
        (
            col_url,
            norm,
            source,
            ext_store,
            company_id,
            company,
            job_title,
            location_raw,
            description_text,
            raw_json,
            now,
            now,
            status,
            reason,
            ats,
        ),
    )
    conn.commit()
    return "insert", int(cur.lastrowid)


