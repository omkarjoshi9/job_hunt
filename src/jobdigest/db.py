def job_hard_status(conn: Conn, job_id: int) -> str:
    row = conn.execute("SELECT hard_status FROM jobs WHERE id = ?", (job_id,)).fetchone()
    if row is None:
        return "pending"
    return str(row["hard_status"])


def _parse_iso(ts: str) -> datetime:
    s = ts.strip()
    if s.endswith("Z"):
        s = s[:-1] + "+00:00"
    dt = datetime.fromisoformat(s)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)


def last_collect_run(conn: Conn) -> RowLike | None:
    return conn.execute(
        "SELECT * FROM runs WHERE kind = 'collect' ORDER BY id DESC LIMIT 1"
    ).fetchone()


def collect_is_ok(conn: Conn, *, max_age_hours: float = 26) -> bool:
    row = last_collect_run(conn)
    if row is None:
        return False
    if str(row["status"]) != "ok":
        return False
    finished = row["finished_at"]
    if not finished:
        return False
    try:
        dt = _parse_iso(str(finished))
    except (ValueError, TypeError):
        return False
    age = datetime.now(timezone.utc) - dt
    return age.total_seconds() <= max_age_hours * 3600


def unscored_pass_jobs(
    conn: Conn, model: str, prompt_version: str
) -> list[RowLike]:
    return conn.execute(
        """
        SELECT jobs.*
        FROM jobs
        WHERE jobs.hard_status = 'pass'
          AND jobs.is_active = 1
          AND NOT EXISTS (
            SELECT 1 FROM scores
            WHERE scores.job_id = jobs.id
              AND scores.model = ?
              AND scores.prompt_version = ?
          )
          AND NOT EXISTS (
            SELECT 1 FROM applications
            WHERE applications.apply_url_norm = jobs.apply_url_norm
          )
        ORDER BY jobs.id ASC
        """,
        (model, prompt_version),
    ).fetchall()


def upsert_score(
    conn: Conn,
    job_id: int,
    model: str,
    prompt_version: str,
    relevant: bool,
    score: float,
    reasons: dict,
) -> None:
    conn.execute(
        """
        INSERT INTO scores (
          job_id, model, prompt_version, relevant, score, reasons_json, created_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(job_id, model, prompt_version) DO UPDATE SET
          relevant = excluded.relevant,
          score = excluded.score,
          reasons_json = excluded.reasons_json,
          created_at = excluded.created_at
        """,
        (
            job_id,
            model,
            prompt_version,
            1 if relevant else 0,
            float(score),
            json.dumps(reasons, separators=(",", ":")),
            utc_now(),
        ),
    )
    conn.commit()


def guest_rows(
    conn: Conn,
    model: str,
    prompt_version: str,
    digest_max: int,
) -> list[RowLike]:
    limit = max(int(digest_max), 0)
    return conn.execute(
        """
        SELECT jobs.*, scores.score AS score, scores.reasons_json AS reasons_json
        FROM jobs
        JOIN scores ON scores.job_id = jobs.id
        WHERE scores.relevant = 1
          AND scores.model = ?
          AND scores.prompt_version = ?
          AND NOT EXISTS (
            SELECT 1 FROM applications
            WHERE applications.apply_url_norm = jobs.apply_url_norm
          )
        ORDER BY scores.score DESC, jobs.id ASC
        LIMIT ?
        """,
        (model, prompt_version, limit),
    ).fetchall()


_APP_STATUSES = frozenset(
    {"applied", "oa", "interview", "offer", "rejected", "ghosted"}
)


def upsert_application(
    conn: Conn,
    *,
    apply_url: str,
    company: str = "",
    title: str = "",
    status: str = "applied",
    notes: str = "",
    source: str = "",
    job_id: int | None = None,
) -> tuple[str, int | None]:
    raw = (apply_url or "").strip()
    if not (
        raw.lower().startswith("http://") or raw.lower().startswith("https://")
    ):
        return "skip", None
    norm = normalize_url(raw)
    if not (
        norm.lower().startswith("http://") or norm.lower().startswith("https://")
    ):
        return "skip", None
    st = (status or "applied").strip().lower()
    if st not in _APP_STATUSES:
        return "skip", None

    job_row = conn.execute(
        "SELECT id, company, title, source FROM jobs WHERE apply_url_norm = ?",
        (norm,),
    ).fetchone()
    resolved_job_id = job_id
    company_s = (company or "").strip()
    title_s = (title or "").strip()
    source_s = (source or "").strip()
    notes_s = notes or ""
    if job_row is not None:
        if resolved_job_id is None:
            resolved_job_id = int(job_row["id"])
        if not company_s:
            company_s = str(job_row["company"] or "")
        if not title_s:
            title_s = str(job_row["title"] or "")
        if not source_s:
            source_s = str(job_row["source"] or "")

    existing = conn.execute(
        "SELECT id FROM applications WHERE apply_url_norm = ?",
        (norm,),
    ).fetchone()
    if existing is not None:
        app_id = int(existing["id"])
        conn.execute(
            """
            UPDATE applications
            SET company = ?, title = ?, status = ?, notes = ?, source = ?, job_id = ?
            WHERE id = ?
            """,
            (company_s, title_s, st, notes_s, source_s, resolved_job_id, app_id),
        )
        conn.commit()
        return "update", app_id
    cur = conn.execute(
        """
        INSERT INTO applications (
          job_id, apply_url_norm, company, title, applied_on, status, source, notes
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (
            resolved_job_id,
            norm,
            company_s,
            title_s,
            utc_now(),
            st,
            source_s,
            notes_s,
        ),
    )
    conn.commit()
    return "insert", int(cur.lastrowid)


def pending_sheet_rows(conn: Conn) -> list[RowLike]:
    return conn.execute(
        """
        SELECT applications.*, jobs.apply_url AS job_apply_url
        FROM applications
        LEFT JOIN jobs ON jobs.id = applications.job_id
        WHERE applications.sheet_row IS NULL
        ORDER BY applications.id
        """
    ).fetchall()


def mark_sheet_synced(
    conn: Conn, application_id: int, sheet_row: int
) -> None:
    conn.execute(
        "UPDATE applications SET sheet_row = ?, synced_at = ? WHERE id = ?",
        (int(sheet_row), utc_now(), int(application_id)),
    )
    conn.commit()
