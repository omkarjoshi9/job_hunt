def test_pg_sql_placeholders_and_returning():
    assert _pg_sql("SELECT * FROM jobs WHERE id = ?") == "SELECT * FROM jobs WHERE id = %s"
    insert = _pg_sql("INSERT INTO runs (kind, started_at, status) VALUES (?, ?, ?)")
    assert insert.count("%s") == 3
    assert "RETURNING id" in insert
    update = _pg_sql("UPDATE jobs SET title = ? WHERE id = ?")
    assert "RETURNING" not in update.upper()
    assert update == "UPDATE jobs SET title = %s WHERE id = %s"
