from jobdigest.db import SCHEMA, SCHEMA_PG, _pg_sql, connect, uses_postgres


def test_connect_path_ignores_database_url(monkeypatch, tmp_path):
    monkeypatch.setenv("DATABASE_URL", "postgresql://example.invalid/db")
    db = tmp_path / "jobs.db"
    assert uses_postgres(db) is False
    conn = connect(db)
    try:
        row = conn.execute("PRAGMA foreign_keys").fetchone()
        assert int(row[0]) == 1
    finally:
        conn.close()


def test_uses_postgres_when_url_set_and_no_path(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", "postgresql://example.invalid/db")
    assert uses_postgres(None) is True
    monkeypatch.delenv("DATABASE_URL", raising=False)
    assert uses_postgres(None) is False


def test_pg_schema_keeps_identity_rules():
    assert "apply_url_norm TEXT NOT NULL UNIQUE" in SCHEMA_PG
    assert "GENERATED BY DEFAULT AS IDENTITY" in SCHEMA_PG
    assert "CHECK (hard_status IN ('pending','pass','reject'))" in SCHEMA_PG
    assert "CHECK (status IN ('running','ok','error'))" in SCHEMA_PG
    assert "jobs_source_ext" in SCHEMA_PG
    assert "UNIQUE(job_id, model, prompt_version)" in SCHEMA_PG
    assert "apply_url_norm TEXT NOT NULL UNIQUE" in SCHEMA


def test_pg_sql_placeholders_and_returning():
    assert _pg_sql("SELECT * FROM jobs WHERE id = ?") == "SELECT * FROM jobs WHERE id = %s"
    insert = _pg_sql("INSERT INTO runs (kind, started_at, status) VALUES (?, ?, ?)")
    assert insert.count("%s") == 3
    assert "RETURNING id" in insert
    update = _pg_sql("UPDATE jobs SET title = ? WHERE id = ?")
    assert "RETURNING" not in update.upper()
    assert update == "UPDATE jobs SET title = %s WHERE id = %s"
