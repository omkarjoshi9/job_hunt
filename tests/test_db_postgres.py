from jobdigest.db import SCHEMA, SCHEMA_PG, _pg_sql, connect, uses_postgres


def test_connect_path_ignores_database_url(monkeypatch, tmp_path):
    monkeypatch.setenv("DATABASE_URL", "postgresql://example.invalid/db")
    db = tmp_path / "jobs.db"
    assert uses_postgres(db) is False
    conn = connect(db)
    try:
        row = conn.execute("PRAGMA foreign_keys").fetchone()
        assert int(row[0]) == 1
    finally:
        conn.close()


def test_uses_postgres_when_url_set_and_no_path(monkeypatch):
    monkeypatch.setenv("DATABASE_URL", "postgresql://example.invalid/db")
    assert uses_postgres(None) is True
    monkeypatch.delenv("DATABASE_URL", raising=False)
    assert uses_postgres(None) is False


