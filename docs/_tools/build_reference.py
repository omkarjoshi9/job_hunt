"""Regenerate docs/reference/symbol-index.md from the source (AST), so it cannot drift."""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from symbols import DOC_PAGE, EXTRA_PAGES, ROOT, heading_slug, scan_all  # noqa: E402

OUT = ROOT / "docs" / "reference" / "symbol-index.md"
DOCS = ROOT / "docs"


def page_headings(page: str) -> list[tuple[str, str]]:
    """(heading text without backticks, anchor) for every heading on a docs page."""
    path = DOCS / page
    if not path.is_file():
        return []
    out: list[tuple[str, str]] = []
    in_fence = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        if in_fence or not line.startswith("#"):
            continue
        title = line.lstrip("#").strip()
        out.append((title.replace("`", ""), heading_slug(title)))
    return out


def find_anchor(name: str, headings: list[tuple[str, str]]) -> str | None:
    """Anchor of the heading that documents ``name`` (``fn`` or ``Class.method``)."""
    short = name.split(".")[-1]
    for text, slug in headings:
        words = [w for w in re.split(r"\W+", text) if w]
        if name in words or short in words or text == name or text == short:
            return slug
    return None


def main() -> int:
    infos = scan_all()
    lines = [
        "# Symbol index",
        "",
        "Generated by `docs/_tools/build_reference.py` from the source AST. Do not edit by hand; "
        "run the script after changing code. Each row links to the page that documents the symbol "
        "(`doc` column); \"no dedicated entry\" means the symbol has no heading of its own on that page "
        "(it may still be explained inside a parent entry - see the coverage report).",
        "",
        f"Totals: **{len(infos)} files**, "
        f"**{sum(1 for i in infos for s in i.symbols if s.kind == 'function')} top-level functions**, "
        f"**{sum(1 for i in infos for s in i.symbols if s.kind == 'class')} classes**, "
        f"**{sum(1 for i in infos for s in i.symbols if s.kind == 'method')} methods**.",
        "",
    ]
    for info in infos:
        page = DOC_PAGE.get(info.path)
        rel_link = f"../{page}" if page else None
        lines.append(f"## `{info.path}`")
        lines.append("")
        lines.append(
            f"{info.lines} lines · documented in "
            + (f"[{page}]({rel_link})" if page else "**(no page mapped)**")
        )
        lines.append("")
        if not info.symbols:
            lines += ["_No functions or classes (constants/re-exports only)._", ""]
            continue
        headings = page_headings(page) if page else []
        extra = EXTRA_PAGES.get(info.path, [])
        lines += ["| symbol | kind | line | length | visibility | doc |", "|---|---|---|---|---|---|"]
        for s in info.symbols:
            anchor = find_anchor(s.name, headings)
            alt = None
            if not anchor:
                for ep in extra:
                    a2 = find_anchor(s.name, page_headings(ep))
                    if a2:
                        alt = f"../{ep}#{a2}"
                        break
            if rel_link and anchor:
                doc = f"[entry](" + f"{rel_link}#{anchor})"
            elif alt:
                doc = f"[entry]({alt})"
            else:
                doc = "no dedicated entry"
            lines.append(
                f"| `{s.name}` | {s.kind} | {s.line} | {s.length} | "
                f"{'private' if s.private else 'public'} | {doc} |"
            )
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(infos)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
