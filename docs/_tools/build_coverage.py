"""Generate docs/reference/coverage-report.md (numbers computed, gaps stated).

    python docs/_tools/check_docs.py --json /tmp/check.json [--mermaid-dir DIR]
    python docs/_tools/build_coverage.py /tmp/check.json
"""

from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from symbols import DOC_PAGE, ROOT, pages_for, scan_all  # noqa: E402

OUT = ROOT / "docs" / "reference" / "coverage-report.md"


def main(check_json: str) -> int:
    check = json.loads(Path(check_json).read_text())
    missing = {(p, n) for p, n, *_ in check["missing"]}
    infos = scan_all()
    rows, tot = [], defaultdict(int)
    big_total = big_head = 0
    for info in infos:
        page = DOC_PAGE.get(info.path)
        text = "\n".join((ROOT / "docs" / pg).read_text() for pg in pages_for(info.path) if (ROOT / "docs" / pg).exists())
        head = mention = absent = 0
        for s in info.symbols:
            short = s.name.split(".")[-1]
            has_heading = (info.path, s.name) not in missing
            if has_heading:
                head += 1
            elif re.search(r"(?<![A-Za-z0-9_])" + re.escape(short) + r"(?![A-Za-z0-9_])", text):
                mention += 1
            else:
                absent += 1
            if s.length >= 10:
                big_total += 1
                big_head += has_heading
        n = len(info.symbols)
        rows.append((info.path, info.lines, n, head, mention, absent, page))
        for k, v in (("files", 1), ("lines", info.lines), ("symbols", n), ("head", head), ("mention", mention), ("absent", absent)):
            tot[k] += v
    classes = sum(1 for i in infos for s in i.symbols if s.kind == "class")
    methods = sum(1 for i in infos for s in i.symbols if s.kind == "method")
    funcs = sum(1 for i in infos for s in i.symbols if s.kind == "function")
    full = [r for r in rows if r[2] and r[5] == 0 and r[4] == 0]
    partial = [r for r in rows if r[2] and r[5] == 0 and r[4] > 0]
    gaps = [r for r in rows if r[5] > 0]
    nosyms = [r for r in rows if r[2] == 0]

    L = ["# Documentation coverage report", "",
         "Generated by `docs/_tools/build_coverage.py` from the AST and the pages in `docs/`; the numbers are recomputed, not hand-counted. "
         "State documented: working tree of 2026-11-03.", "",
         "## Totals", "",
         "| Measure | Count |", "|---|---|",
         f"| Source files discovered (`src/jobdigest/**`, `scripts/`) | {tot['files']} |",
         f"| Source files with a documentation page mapped | {sum(1 for r in rows if r[6])} |",
         f"| Source lines | {tot['lines']} |",
         f"| Top-level functions | {funcs} |", f"| Methods | {methods} |", f"| Classes | {classes} |",
         f"| **Symbols (functions + methods + classes)** | **{tot['symbols']}** |",
         f"| Symbols with their own heading (full entry or compact entry) | {tot['head']} |",
         f"| Symbols explained inside another entry or table on their page (no own heading) | {tot['mention']} |",
         f"| Symbols not mentioned on their page | {tot['absent']} |",
         f"| Symbols of 10+ lines with their own heading | {big_head} of {big_total} |",
         f"| Markdown files in `docs/` | {check['markdown_files']} |",
         f"| `path:line` references checked and valid | {check['refs_checked']} |",
         f"| `Location` lines verified against the real `def`/`class`/constant | {check['locations_verified']} |",
         f"| Mermaid diagrams parsed by the real Mermaid parser | {check['mermaid_blocks']} ({check['mermaid_failed']} failed) |",
         f"| Link/anchor/reference errors found by `check_docs.py` | {len(check['errors'])} |", ""]
    L += ["Test files (62) are **not** documented function by function; they are covered by the [test map](../testing/test-map.md), the "
          "[strategy](../testing/strategy.md) and [e2e page](../testing/e2e-and-fixtures.md) (see gaps below).", ""]

    def table(title, subset):
        L.extend([f"## {title}", "", "| File | Lines | Symbols | Own heading | In another entry | Absent | Page |", "|---|---|---|---|---|---|---|"])
        for p, ln, n, h, m, a, page in subset:
            L.append(f"| `{p}` | {ln} | {n} | {h} | {m} | {a} | " + (f"[{page}](../{page})" if page else "-") + " |")
        L.append("")

    L += ["## Coverage by module", "",
          "*Own heading* = a `###` entry for the symbol (full step-by-step or compact form). *In another entry* = the symbol is explained inside a "
          "parent function's entry or a table on the same page. *Absent* = not mentioned on its page.", ""]
    table("Every source file", rows)

    L += ["## Classification", "",
          f"* **Fully documented** (every symbol has its own entry): {len(full)} files.",
          f"* **Documented, some symbols only inside a parent entry or table**: {len(partial)} files.",
          f"* **Gaps (symbols not mentioned on their page)**: {len(gaps)} files" + (": " + ", ".join(f"`{r[0]}`" for r in gaps) if gaps else "."),
          f"* **No symbols** (constants/re-exports only, described in prose): {len(nosyms)} files.", ""]
    if partial:
        L += ["Files in the *partial* group:", ""] + [f"* `{r[0]}` - {r[4]} of {r[2]} symbols without their own heading" for r in partial] + [""]

    L += ["## Known gaps and limitations of this documentation", "",
          "* **Compact entries are not full walkthroughs.** Trivial helpers (one-liners, `__init__` methods that only store arguments, small row/attribute accessors) "
          "get a location, signature and two or three sentences, not the numbered step-by-step. Complex functions (for example `upsert_job`, `collect.run`, "
          "`hard_filter`, `score._score_batch`, `rank.select_diverse`, `bot._handle_callback`) have full walkthroughs.",
          "* **Research scripts are summarised.** `scripts/probe_ats_tokens.py` and `probe_ats_tokens_wave2.py` carry large hand-curated data dictionaries "
          "(`LEVER_NAMES`, `ASHBY_NAMES`, `WORKABLE_NOTABLE`, `WAVE2`) that are described, not enumerated, and the scripts have no tests.",
          "* **Tests are mapped, not walked.** The 62 test files are listed with what each covers and pins, and the helpers/fakes are documented; individual test "
          "bodies in the largest files (`test_hard_filter`, `test_sheet`, `test_legitimacy`, `test_priors`, `test_bot`) were summarised from names and spot reads.",
          "* **Not exercised live.** Postgres code paths (placeholder rewriting, `RETURNING`, constraint migration), real OpenRouter and Telegram HTTP, "
          "Google Sheets, and browser-based portals were documented from the code and offline runs only. Statements about vendor behaviour (which ATS "
          "redirect on a bad slug, BambooHR payload shape) are marked as inferred in the relevant pages.",
          "* **Data and generated files.** `data/*.tsv` are described (columns, sources, row counts, readers) but not reproduced. `src/jobdigest.egg-info/` is "
          "generated and ignored. `.cursor/plans/` holds stale planning notes and is not documented except as a drift warning in the infra pages.",
          "* **Line numbers drift.** `path:line` references are exact for the documented working tree; the function name is the stable identifier. "
          "`check_docs.py` re-verifies every `Location` line.",
          "* **Examples use the example profile.** `config/profile.yaml` is not in the repository, so outputs that depend on the profile were produced with "
          "`config/profile.example.yaml` (`min_yoe_reject` 3, empty `top_companies`).",
          "* **Mermaid** diagrams are syntax-checked by the real parser; the parser does not check that a diagram is *semantically* right, which was verified by hand "
          "against the code when each diagram was written.", "",
          "## How to refresh", "",
          "```bash",
          "python docs/_tools/build_reference.py",
          "python docs/_tools/check_docs.py --mermaid-dir <dir with mermaid and jsdom installed> --json /tmp/check.json",
          "python docs/_tools/build_coverage.py /tmp/check.json",
          "```", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
