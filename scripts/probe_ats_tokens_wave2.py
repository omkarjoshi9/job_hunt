def main() -> int:
    data = yaml.safe_load(OUT.read_text(encoding="utf-8"))
    existing = {(c["ats"], c["token"]) for c in data["companies"]}
    todo = []
    for token, (name, notes) in WAVE2.items():
        if skipped(token, token):
            continue
        if token in LEVER_NAMES:
            continue
        if ("lever", token) in existing:
            continue
        todo.append((token, name, notes))
    print(f"Wave2 Lever candidates: {len(todo)}", flush=True)
    headers = {"User-Agent": UA, "Accept": "application/json"}
    added = []
    with httpx.Client(headers=headers, follow_redirects=True) as client:
        def run(item):
            token, name, notes = item
            return token, name, notes, _lever_hit(token, probe_lever(client, token))

        with ThreadPoolExecutor(max_workers=10) as pool:
            futs = [pool.submit(run, it) for it in todo]
            done = 0
            for fut in as_completed(futs):
                done += 1
                if done % 20 == 0:
                    print(f"  {done}/{len(todo)}", flush=True)
                token, name, notes, hit = fut.result()
                if not hit:
                    continue
                cid = re.sub(r"[^a-z0-9-]+", "-", token.lower()).strip("-")
                jobs = hit["jobs"]
                note_parts = [notes]
                if hit.get("india"):
                    note_parts.append("India locations present on live board")
                if jobs == 0:
                    note_parts.append("valid empty board at probe time")
                if hit.get("region") == "eu":
                    note_parts.append("EU Lever host api.eu.lever.co")
                if hit.get("sample"):
                    note_parts.append(f"sample role: {hit['sample'][:80]}")
                note_parts.append(
                    f"evidence: GET {hit.get('api')} → 200 JSON array ({jobs} jobs); "
                    "slug in Feashliaa/job-board-aggregator lever_companies.json and/or public jobs.lever.co board"
                )
                added.append(
                    {
                        "id": cid,
                        "name": name,
                        "ats": "lever",
                        "token": token,
                        "notes": "; ".join(note_parts),
                        "confidence": confidence(jobs, True),
                    }
                )
    data["companies"].extend(added)
    data["companies"].sort(key=lambda c: (c["ats"], c["name"].lower()))
    counts = {"lever": 0, "ashby": 0, "workable": 0}
    for c in data["companies"]:
        counts[c["ats"]] += 1
    data["counts"] = counts
    OUT.write_text(
        yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100),
        encoding="utf-8",
    )
    print("added", len(added), "counts", counts)
    return 0


if __name__ == "__main__":
    sys.exit(main())
